# ── Helpers ───────────────────────────────────────────────────────────────────
def _load_json(path: Path) -> dict:
    if not path.exists():
        raise HTTPException(status_code=404, detail=f"Artifact not found: {path.name}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise HTTPException(status_code=500, detail=f"Corrupt artifact file: {e}")


def _load_jsonl(path: Path, limit: int = 50) -> list[dict]:
    if not path.exists():
        return []
    lines = path.read_text(encoding="utf-8").strip().splitlines()
    entries = []
    for line in reversed(lines[-limit:]):
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return entries


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


# ── Health ────────────────────────────────────────────────────────────────────
@app.get("/api/health", tags=["System"])
def health():
    """Check server health and artifact file availability."""
    artifacts = {}
    for name in ["risk_register.json", "velocity_log.json", "stakeholder_map.json"]:
        path = ARTIFACTS_DIR / name
        artifacts[name] = {
            "exists": path.exists(),
            "size_bytes": path.stat().st_size if path.exists() else 0,
            "last_modified": datetime.fromtimestamp(
                path.stat().st_mtime, tz=timezone.utc
            ).isoformat() if path.exists() else None,
        }
    return {
        "status": "ok",
        "timestamp": _now(),
        "artifacts": artifacts,
        "python": sys.version,
    }


# ── Risk Register ─────────────────────────────────────────────────────────────
@app.get("/api/risks", tags=["Risk Register"])
def get_risks(
    status:   Optional[str] = Query(None, description="Filter by status: Open, Mitigating, Resolved"),
    category: Optional[str] = Query(None, description="Filter by category: Technical, Schedule, Resource, Quality, External"),
    min_impact: Optional[int] = Query(None, ge=1, le=10, description="Minimum impact score"),
):
    """Return all risks with optional filters."""
    data = _load_json(ARTIFACTS_DIR / "risk_register.json")
    risks = data.get("risks", [])

    if status:
        risks = [r for r in risks if r.get("status", "").lower() == status.lower()]
    if category:
        risks = [r for r in risks if r.get("category", "").lower() == category.lower()]
    if min_impact is not None:
        risks = [r for r in risks if r.get("impact_score", 0) >= min_impact]

    # Sort by risk_score descending (highest risk first)
    risks = sorted(risks, key=lambda r: r.get("risk_score", 0), reverse=True)

    return {
        "project_id":   data.get("project_id"),
        "last_updated": data.get("last_updated"),
        "total":        len(risks),
        "risks":        risks,
    }


@app.get("/api/risks/summary", tags=["Risk Register"])
def get_risk_summary():
    """Aggregated risk statistics for dashboard KPI cards."""
    data  = _load_json(ARTIFACTS_DIR / "risk_register.json")
    risks = data.get("risks", [])

    by_status   = {}
    by_category = {}
    by_prob     = {}

    for r in risks:
        s = r.get("status", "Unknown")
        c = r.get("category", "Unknown")
        p = r.get("probability", "Unknown")
        by_status[s]   = by_status.get(s, 0) + 1
        by_category[c] = by_category.get(c, 0) + 1
        by_prob[p]     = by_prob.get(p, 0) + 1

    open_risks    = [r for r in risks if r.get("status") in ("Open", "Mitigating")]
    critical      = [r for r in risks if r.get("impact_score", 0) >= 8]
    avg_impact    = round(sum(r.get("impact_score", 0) for r in risks) / len(risks), 1) if risks else 0

    return {
        "total":          len(risks),
        "open":           len(open_risks),
        "critical":       len(critical),
        "avg_impact":     avg_impact,
        "by_status":      by_status,
        "by_category":    by_category,
        "by_probability": by_prob,
        "last_updated":   data.get("last_updated"),
    }


@app.get("/api/risks/{risk_id}", tags=["Risk Register"])
def get_risk(risk_id: str):
    """Return a single risk entry by ID."""
    data  = _load_json(ARTIFACTS_DIR / "risk_register.json")
    risks = data.get("risks", [])
    match = next((r for r in risks if r["risk_id"].upper() == risk_id.upper()), None)
    if not match:
        raise HTTPException(status_code=404, detail=f"Risk '{risk_id}' not found")
    return match


# ── Velocity Log ──────────────────────────────────────────────────────────────
@app.get("/api/velocity", tags=["Velocity"])
def get_velocity():
    """Return full sprint velocity log."""
    data = _load_json(ARTIFACTS_DIR / "velocity_log.json")
    sprints = data.get("sprints", [])

    # Enrich each sprint with computed velocity percentage
    for s in sprints:
        planned   = s.get("metrics", {}).get("story_points_planned", 0)
        completed = s.get("metrics", {}).get("story_points_completed", 0)
        s["velocity_pct"] = round((completed / planned * 100), 1) if planned > 0 else 0

    return {
        "project_id":   data.get("project_id"),
        "last_updated": data.get("last_updated"),
        "sprint_count": len(sprints),
        "sprints":      sprints,
    }


@app.get("/api/velocity/current", tags=["Velocity"])
def get_current_sprint():
    """Return the currently active sprint."""
    data    = _load_json(ARTIFACTS_DIR / "velocity_log.json")
    sprints = data.get("sprints", [])
    active  = next((s for s in sprints if s.get("status") == "Active"), None)
    if not active:
        # Fall back to most recent sprint
        active = sprints[-1] if sprints else None
    if not active:
        raise HTTPException(status_code=404, detail="No active sprint found")

    planned   = active.get("metrics", {}).get("story_points_planned", 0)
    completed = active.get("metrics", {}).get("story_points_completed", 0)
    active["velocity_pct"] = round((completed / planned * 100), 1) if planned > 0 else 0
    return active


