"""
api/main.py
-----------
FastAPI server that exposes the live PMBOK artifact files as REST endpoints.
The React dashboard calls these instead of using hardcoded seed data.

Endpoints:
    GET  /api/risks                 → full risk_register.json
    GET  /api/risks/{risk_id}       → single risk entry
    GET  /api/velocity              → full velocity_log.json
    GET  /api/velocity/{sprint_id}  → single sprint entry
    GET  /api/stakeholders          → stakeholder_map.json
    GET  /api/pipeline/runs         → last N pipeline audit log entries
    GET  /api/pipeline/stats        → aggregated run statistics
    GET  /api/health                → server + artifact health check
    POST /api/pipeline/trigger      → manually trigger an agent pipeline run

Start:
    uvicorn api.main:app --reload --port 8000

    OR via Docker Compose (see docker-compose.yml)
"""

