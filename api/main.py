# ── Pipeline Audit Log ────────────────────────────────────────────────────────
@app.get("/api/pipeline/runs", tags=["Pipeline"])
def get_pipeline_runs(limit: int = Query(50, ge=1, le=500)):
    """Return the last N pipeline audit log entries, newest first."""
    entries = _load_jsonl(LOGS_DIR / "pipeline_audit.jsonl", limit=limit)
    return {
        "total":   len(entries),
        "limit":   limit,
        "runs":    entries,
    }


@app.get("/api/pipeline/stats", tags=["Pipeline"])
def get_pipeline_stats():
    """Aggregated pipeline statistics for dashboard."""
    entries = _load_jsonl(LOGS_DIR / "pipeline_audit.jsonl", limit=500)
    if not entries:
        return {"total_runs": 0, "message": "No pipeline runs recorded yet"}

    total        = len(entries)
    successful   = sum(1 for e in entries if e.get("success"))
    failed       = total - successful
    total_tokens = sum(e.get("input_tokens", 0) + e.get("output_tokens", 0) for e in entries)
    avg_duration = round(sum(e.get("duration_sec", 0) for e in entries) / total, 2)

    by_type = {}
    for e in entries:
        t = e.get("output_type", "UNKNOWN")
        by_type[t] = by_type.get(t, 0) + 1

    by_provider = {}
    for e in entries:
        p = e.get("provider", "unknown")
        by_provider[p] = by_provider.get(p, 0) + 1

    return {
        "total_runs":    total,
        "successful":    successful,
        "failed":        failed,
        "success_rate":  round(successful / total * 100, 1),
        "total_tokens":  total_tokens,
        "avg_duration_sec": avg_duration,
        "by_output_type":  by_type,
        "by_provider":     by_provider,
        "latest_run":      entries[0] if entries else None,
    }


# ── Manual pipeline trigger ───────────────────────────────────────────────────
class TriggerRequest(BaseModel):
    repo:         str
    sprint_id:    str = "SP-03"
    sprint_start: str = "2026-05-12"
    sprint_end:   str = "2026-05-25"
    provider:     Optional[str] = None
    dry_run:      bool = True


def _run_pipeline_background(req: TriggerRequest):
    """Run agent_pipeline.py as a subprocess (non-blocking)."""
    cmd = [
        sys.executable, str(SRC_DIR / "agent_pipeline.py"),
        "--repo",   req.repo,
        "--sprint", req.sprint_id,
        "--start",  req.sprint_start,
        "--end",    req.sprint_end,
        "--output", "json",
    ]
    if req.provider:
        cmd += ["--provider", req.provider]
    if req.dry_run:
        cmd.append("--dry-run")

    try:
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=120,
            env={**os.environ},
        )
        log_path = LOGS_DIR / "api_triggers.jsonl"
        entry = {
            "timestamp":   _now(),
            "repo":        req.repo,
            "returncode":  result.returncode,
            "stdout":      result.stdout[:2000],
            "stderr":      result.stderr[:500],
        }
        with open(log_path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry) + "\n")
    except Exception as e:
        print(f"Background pipeline run failed: {e}")


@app.post("/api/pipeline/trigger", tags=["Pipeline"])
def trigger_pipeline(req: TriggerRequest, background_tasks: BackgroundTasks):
    """
    Manually trigger an agent pipeline run.
    Runs in the background — poll /api/pipeline/runs to see the result.
    """
    if not os.getenv("GITHUB_TOKEN"):
        raise HTTPException(
            status_code=400,
            detail="GITHUB_TOKEN is not set. Cannot trigger pipeline."
        )
    background_tasks.add_task(_run_pipeline_background, req)
    return {
        "status":   "triggered",
        "message":  "Pipeline run started in background. Poll /api/pipeline/runs for results.",
        "dry_run":  req.dry_run,
        "repo":     req.repo,
        "timestamp": _now(),
    }


# ── Dashboard summary (single call for the React app) ────────────────────────
@app.get("/api/dashboard", tags=["Dashboard"])
def get_dashboard():
    """
    Single endpoint that returns everything the React dashboard needs.
    Minimises client-side fetch calls.
    """
    risks_data    = _load_json(ARTIFACTS_DIR / "risk_register.json")
    velocity_data = _load_json(ARTIFACTS_DIR / "velocity_log.json")
    pipeline_runs = _load_jsonl(LOGS_DIR / "pipeline_audit.jsonl", limit=20)

    sprints = velocity_data.get("sprints", [])
    for s in sprints:
        planned   = s.get("metrics", {}).get("story_points_planned", 0)
        completed = s.get("metrics", {}).get("story_points_completed", 0)
        s["velocity_pct"] = round((completed / planned * 100), 1) if planned > 0 else 0

    risks         = risks_data.get("risks", [])
    open_risks    = [r for r in risks if r.get("status") in ("Open", "Mitigating")]
    critical      = [r for r in risks if r.get("impact_score", 0) >= 8]
    active_sprint = next((s for s in sprints if s.get("status") == "Active"), sprints[-1] if sprints else {})

    total_tokens = sum(
        e.get("input_tokens", 0) + e.get("output_tokens", 0) for e in pipeline_runs
    )

    return {
        "meta": {
            "generated_at":   _now(),
            "risks_updated":  risks_data.get("last_updated"),
            "velocity_updated": velocity_data.get("last_updated"),
        },
        "kpis": {
            "open_risks":      len(open_risks),
            "critical_risks":  len(critical),
            "active_blockers": len(active_sprint.get("blockers", [])),
            "sprint_velocity": active_sprint.get("velocity_pct", 0),
            "pipeline_runs":   len(pipeline_runs),
            "total_tokens":    total_tokens,
            "ai_confidence":   active_sprint.get("ai_confidence", 0),
            "current_sprint":  active_sprint.get("sprint_id", "N/A"),
        },
        "risks":         sorted(risks, key=lambda r: r.get("risk_score", 0), reverse=True),
        "sprints":       sprints,
        "pipeline_runs": pipeline_runs,
    }
